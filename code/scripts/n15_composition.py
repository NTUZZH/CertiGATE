#!/usr/bin/env python3
"""N15: who is in the scored sets of the decision-time comparison (from logs only).

For the direct benchmark at the decision instant (1,356 priced proposals) and the
cost levels delta = 0.20 (the tolerance) and delta = 0.10, this script reports

  A  the class and edit-type composition of the costly and the low-cost set,
     with the proposals that carry no operation counted separately;
  B  for each first price on the known board (K) and under full information
     (FI): costly proposals applied, by class and edit type, low-cost proposals
     referred, by class, and the referral share over proposals with operations;
  C  the same with the second price on field edits (known board);
  D  the same comparison on the proposals whose known-board bound is at least
     the floor of one weighted business hour.

It reuses the loaders, the scoring and the cluster bootstrap of n13_fromlogs.py,
runs no solve and no model call, and asserts the published cells first.
Outputs: analysis/N15_macros.tex (prefix \\nFifteen), analysis/N15_summary.md.
Run: taskset -c 12-13 python3 code/scripts/n15_composition.py
"""
import sys
from collections import Counter, OrderedDict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import n13_fromlogs as n13  # noqa: E402

VERSION = "l1-n15-composition-1"
OUT_TEX = n13.ANALYSIS / "N15_macros.tex"
OUT_MD = n13.ANALYSIS / "N15_summary.md"
DELTAS = OrderedDict([("Twenty", 0.20), ("Ten", 0.10)])
TOK = OrderedDict([("G-CERT", "Cert"), ("G-CERT-M", "CertM"), ("D-REL1", "RelOne"),
                   ("D-REL2", "RelTwo"), ("D-ABS", "Abs")])
CLS = OrderedDict([("benign", "Benign"), ("V1", "VOne"), ("V3", "VThree"), ("V4", "VFour"),
                   ("V5", "VFive"), ("V6", "VSix")])
LINES = ["% N15 macros ({}); generated by code/scripts/n15_composition.py from the logged "
         "results only (no solve, no model call)".format(VERSION)]
NAMES = set()
MD = []
NCHECK = [0]


def check(what, ok, detail=""):
    if not ok:
        raise SystemExit("[n15] ASSERTION FAILED: {} ({})".format(what, detail))
    NCHECK[0] += 1


def add(name, value):
    full = "nFifteen" + name
    if not full.isalpha():
        raise SystemExit("macro name not alphabetic: " + full)
    if full in NAMES:
        raise SystemExit("duplicate macro " + full)
    NAMES.add(full)
    LINES.append("\\newcommand{\\" + full + "}{" + str(value) + "}")


def grp(n):
    return "{:,}".format(n).replace(",", "{,}")


def pct(k, n):
    return "{:.1f}\\%".format(100.0 * k / n) if n else "n/a"


def pctv(x):
    return "{:.1f}\\%".format(100.0 * x)


RULES = OrderedDict([("atc", "Atc"), ("wspt", "Wspt"), ("pfifo", "Pfifo"), ("edd", "Edd")])
RULE_SET = {"G-CERT": 0.20, "G-CERT-M": 0.20, "D-REL1": 0.02, "D-REL2": 0.02, "D-ABS": 0.8119}


def section_e(recs):
    """E  the four dispatching rules at both cost levels, from analysis/N14_rows.csv:
    costly proposals applied on the known board, with full information and under both,
    and low-cost proposals referred on the known board."""
    rows = n13.read_csv(n13.ANALYSIS / "N14_rows.csv")
    by_rule = OrderedDict((r, []) for r in RULES)
    for r in rows:
        if r["rule"] in by_rule and r["priced_K"] == "True":
            by_rule[r["rule"]].append(r)
    MD.extend(["## Four dispatching rules (analysis/N14_rows.csv)", ""])
    for dtok, delta in DELTAS.items():
        MD.extend(["delta = {:.2f}".format(delta), "",
                   "| rule | design | applied K | applied FI | applied under both | referred K |",
                   "|---|---|---|---|---|---|"])
        for rule, rt in RULES.items():
            costly, low = [], []
            for r in by_rule[rule]:
                lo, hi = n13.fnum(r["orig_m_lo"]), n13.fnum(r["orig_m_hi"])
                if lo is None:
                    continue
                if lo > delta:
                    costly.append(r)
                elif hi <= delta:
                    low.append(r)
            add("Disp" + rt + "Costly" + dtok, len(costly))
            add("Disp" + rt + "Low" + dtok, grp(len(low)))
            for g, gt in TOK.items():
                def ref(r, rd, g=g):
                    v = n13.fnum(r["p_{}_{}".format(rd, g)])
                    return v is not None and v > RULE_SET[g]
                mk = [r for r in costly if not ref(r, "K")]
                mf = [r for r in costly if not ref(r, "FI")]
                both = [r for r in mk if not ref(r, "FI")]
                fk = [r for r in low if ref(r, "K")]
                pre = "Disp" + rt + gt
                add(pre + "Miss" + dtok, len(mk))
                add(pre + "MissShare" + dtok, pct(len(mk), len(costly)))
                add(pre + "MissFI" + dtok, len(mf))
                add(pre + "MissBoth" + dtok, len(both))
                add(pre + "MissField" + dtok,
                    sum(1 for r in mk if r["split"] == "field_changing"))
                add(pre + "Fr" + dtok, len(fk))
                add(pre + "FrShare" + dtok, pct(len(fk), len(low)))
                MD.append("| {} | {} | {}/{} | {} | {} | {}/{} |".format(
                    rule, g, len(mk), len(costly), len(mf), len(both), len(fk), len(low)))
                if rule == "atc":
                    base_c = [r for r in recs if n13.costly_of(r, delta) == 1]
                    base_m = sum(1 for r in base_c if not n13.refers(r, g))
                    check("ATC row equals the direct benchmark ({} {})".format(g, delta),
                          (len(costly), len(mk)) == (len(base_c), base_m),
                          (len(costly), len(mk), len(base_c), base_m))
        MD.append("")


def main():
    hashes, items_dt, pub, boot, fc = n13.load_inputs()
    by = {r["item_id"]: r for r in items_dt if r["set"] == "published"}
    K, FI = fc["K"], fc["FI"]
    recs = []
    for iid, r in K.items():
        it = by[iid]
        g = (it["dt_obj_orig"] - it["an_lb"]) / max(it["an_lb"], n13.D.FLOOR_BH)
        recs.append(dict(r, sp=(g > n13.TAU), lb_k=it["dt_lb"], fi=FI[iid]))
    check("1,356 priced proposals", len(recs) == 1356, len(recs))
    n_empty = sum(1 for r in recs if r["split"] == "empty")
    add("Priced", grp(len(recs)))
    add("Empty", n_empty)
    add("WithOps", grp(len(recs) - n_empty))
    pos = [r for r in recs if r["lb_k"] >= n13.D.FLOOR_BH]
    add("PosBound", len(pos))
    add("ZeroBound", sum(1 for r in recs if r["lb_k"] == 0))
    add("FloorBinds", len(recs) - len(pos))
    add("FloorBindsShare", pct(len(recs) - len(pos), len(recs)))
    check("floor binds on 701 of 1,356", len(recs) - len(pos) == 701, len(recs) - len(pos))
    MD.extend(["# N15: composition of the scored sets ({})".format(VERSION), "",
               "Direct benchmark at the decision instant, {} priced proposals, {} without "
               "operations, {} with a known-board bound of at least one weighted bh.".format(
                   len(recs), n_empty, len(pos)), ""])

    for dtok, delta in DELTAS.items():
        costly = [r for r in recs if n13.costly_of(r, delta) == 1]
        low = [r for r in recs if n13.costly_of(r, delta) == 0]
        check("every proposal is decided at delta {}".format(delta),
              len(costly) + len(low) == len(recs))
        low_ops = [r for r in low if r["split"] != "empty"]
        add("Costly" + dtok, len(costly))
        add("Low" + dtok, grp(len(low)))
        add("LowWithOps" + dtok, len(low_ops))
        cc, lc = Counter(r["primary_class"] for r in costly), Counter(r["primary_class"] for r in low)
        for c, ct in CLS.items():
            add("Costly" + ct + dtok, cc.get(c, 0))
            add("Low" + ct + dtok, lc.get(c, 0))
        check("no class outside the table", set(cc) | set(lc) <= set(CLS), set(cc) | set(lc))
        add("CostlyField" + dtok, sum(1 for r in costly if r["split"] == "field_changing"))
        add("CostlySeq" + dtok, sum(1 for r in costly if r["split"] == "sequencing_only"))
        add("LowField" + dtok, sum(1 for r in low if r["split"] == "field_changing"))
        add("LowSeq" + dtok, sum(1 for r in low if r["split"] == "sequencing_only"))
        MD.extend(["## delta = {:.2f}: {} costly, {} low-cost ({} with operations)".format(
            delta, len(costly), len(low), len(low_ops)), "",
            "Costly by class: {}; by edit type: {}.".format(
                dict(cc), dict(Counter(r["split"] for r in costly))),
            "Low-cost by class: {}; by edit type: {}.".format(
                dict(lc), dict(Counter(r["split"] for r in low))), "",
            "| design | check | applied K | field edits among them | applied FI | applied under "
            "both | referred K | of them benign | share | share over proposals with "
            "operations | referred FI |", "|---|---|---|---|---|---|---|---|---|---|---|"])
        for g, gt in TOK.items():
            for stok, sname, flag_k in (
                    ("", "first price", lambda r, g=g: n13.refers(r, g)),
                    ("Two", "with the second price on field edits",
                     lambda r, g=g: n13.refers(r, g) or (r["split"] == "field_changing"
                                                         and r["sp"]))):
                s = n13.score(boot, recs, flag_k, delta)
                check("counts", s["costly"] == len(costly) and s["cheap"] == len(low))
                miss = [r for r, m in zip(s["_costly"], s["_miss"]) if m]
                fr = [r for r, f in zip(s["_cheap"], s["_fr"]) if f]
                miss_fi = [r for r in costly if not n13.refers(r["fi"], g)]
                fr_fi = [r for r in low if n13.refers(r["fi"], g)]
                both = [r for r in miss if not n13.refers(r["fi"], g)]
                pre = gt + stok
                add(pre + "Miss" + dtok, len(miss))
                add(pre + "MissShare" + dtok, pct(len(miss), len(costly)))
                add(pre + "MissField" + dtok, sum(1 for r in miss if r["split"] == "field_changing"))
                add(pre + "MissVFour" + dtok, sum(1 for r in miss if r["primary_class"] == "V4"))
                add(pre + "Fr" + dtok, len(fr))
                add(pre + "FrShare" + dtok, pct(len(fr), len(low)))
                add(pre + "FrShareLo" + dtok, pctv(s["fr_lo"]))
                add(pre + "FrShareHi" + dtok, pctv(s["fr_hi"]))
                add(pre + "FrWithOpsShare" + dtok, pct(len(fr), len(low_ops)))
                add(pre + "FrBenign" + dtok, sum(1 for r in fr if r["primary_class"] == "benign"))
                check("no proposal without operations is referred",
                      all(r["split"] != "empty" for r in fr))
                if not stok:
                    add(gt + "MissFI" + dtok, len(miss_fi))
                    add(gt + "MissBoth" + dtok, len(both))
                    add(gt + "FrFI" + dtok, len(fr_fi))
                    add(gt + "FrFIShare" + dtok, pct(len(fr_fi), len(low)))
                MD.append("| {} | {} | {}/{} | {} | {} | {} | {}/{} | {} | {} | {} | {} |".format(
                    g, sname, len(miss), len(costly),
                    sum(1 for r in miss if r["split"] == "field_changing"),
                    len(miss_fi) if not stok else "", len(both) if not stok else "",
                    len(fr), len(low), sum(1 for r in fr if r["primary_class"] == "benign"),
                    pct(len(fr), len(low)).replace("\\", ""),
                    pct(len(fr), len(low_ops)).replace("\\", ""),
                    len(fr_fi) if not stok else ""))
                # the published cells
                if g == "G-CERT-M" and not stok:
                    exp = {0.10: (26, 31, 0), 0.20: (18, 18, 14)}[delta]
                    check("G-CERT-M alone, published cells",
                          (len(miss), len(miss_fi), len(fr)) == exp, (len(miss), len(miss_fi), len(fr)))
                if g == "G-CERT-M" and stok:
                    exp = {0.10: (7, 6), 0.20: (0, 21)}[delta]
                    check("G-CERT-M with the second price, N13 J cells",
                          (len(miss), len(fr)) == exp, (len(miss), len(fr)))
        # positive-bound subset, first prices
        pc = [r for r in pos if n13.costly_of(r, delta) == 1]
        pl = [r for r in pos if n13.costly_of(r, delta) == 0]
        add("PosCostly" + dtok, len(pc))
        add("PosLow" + dtok, len(pl))
        MD.extend(["", "Proposals with a known-board bound of at least one weighted bh: {} "
                   "costly, {} low-cost.".format(len(pc), len(pl)), "",
                   "| design | applied K | applied FI | referred K | referred FI |",
                   "|---|---|---|---|---|"])
        for g, gt in TOK.items():
            mk = sum(1 for r in pc if not n13.refers(r, g))
            mf = sum(1 for r in pc if not n13.refers(r["fi"], g))
            fk = sum(1 for r in pl if n13.refers(r, g))
            ff = sum(1 for r in pl if n13.refers(r["fi"], g))
            add("Pos" + gt + "Miss" + dtok, mk)
            add("Pos" + gt + "MissShare" + dtok, pct(mk, len(pc)))
            add("Pos" + gt + "MissFI" + dtok, mf)
            add("Pos" + gt + "MissFIShare" + dtok, pct(mf, len(pc)))
            add("Pos" + gt + "Fr" + dtok, fk)
            add("Pos" + gt + "FrShare" + dtok, pct(fk, len(pl)))
            add("Pos" + gt + "FrFI" + dtok, ff)
            add("Pos" + gt + "FrFIShare" + dtok, pct(ff, len(pl)))
            MD.append("| {} | {}/{} | {}/{} | {}/{} | {}/{} |".format(
                g, mk, len(pc), mf, len(pc), fk, len(pl), ff, len(pl)))
        MD.append("")
    section_e(recs)
    OUT_TEX.write_text("\n".join(LINES) + "\n", encoding="utf-8")
    OUT_MD.write_text("\n".join(MD + ["", "{} assertions passed; {} macros.".format(
        NCHECK[0], len(NAMES))]) + "\n", encoding="utf-8")
    print("[n15] {} macros, {} assertions passed".format(len(NAMES), NCHECK[0]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
