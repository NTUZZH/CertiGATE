#!/usr/bin/env python3
"""Exact one-sided bound for the withheld column of the practitioner audit.

Reads analysis/N22_numbers.json (written by n22_audit_annotator.py). On every
judgement where the benchmark intends a referral the panel rejects or refers
the proposal, so a case-cluster bootstrap returns a degenerate interval. This
script counts the cases behind those judgements and writes the exact one-sided
95% lower bound on the share of cases that the panel withholds, with each case
counted once: alpha ** (1 / cases) for cases withheld by every member.

Outputs analysis/N22b_macros.tex (copied to the manuscript's macro file).
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
ALPHA = 0.05
CLASSES = ("V3", "V4", "V5", "V6")


def main():
    d = json.loads((ROOT / "analysis" / "N22_numbers.json").read_text())
    members = len(d["per_rater"])
    assert members == 5, members
    pooled = d["measures"]["pooled"]["withhold_when_refer"]
    cases = 0
    judgements = 0
    for c in CLASSES:
        m = d["measures"]["by_class"][c]["withhold_when_refer"]
        assert m["num"] == m["den"], (c, m)          # withheld on every judgement
        assert m["den"] % members == 0, (c, m)
        cases += m["den"] // members
        judgements += m["den"]
    assert d["measures"]["by_class"]["benign"]["withhold_when_refer"] is None
    assert judgements == pooled["den"] == pooled["num"], (judgements, pooled)
    bound = ALPHA ** (1.0 / cases)
    lines = [
        "% Generated by code/scripts/n22b_withheld_bound.py from analysis/N22_numbers.json",
        "\\newcommand{\\nTwentyTwoAuditWithholdCases}{%d}" % cases,
        "\\newcommand{\\nTwentyTwoAuditWithholdCaseBound}{%.1f\\%%}" % (100 * bound),
        "",
    ]
    out = ROOT / "analysis" / "N22b_macros.tex"
    out.write_text("\n".join(lines))
    print("cases", cases, "judgements", judgements, "bound %.4f" % bound)


if __name__ == "__main__":
    main()
